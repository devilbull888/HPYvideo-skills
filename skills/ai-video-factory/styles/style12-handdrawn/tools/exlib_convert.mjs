// Convert .excalidrawlib files → src/sketch/exlib-data.ts
// Excalidraw elements store *geometry* (points/shapes); the sketchy rendering is
// applied by Rough.js at draw time — same engine we use, so conversion is a pure
// coordinate transform. Usage: node tools/exlib_convert.mjs
import { readFileSync, writeFileSync, readdirSync } from "node:fs";
import path from "node:path";

const DIR = path.resolve(path.dirname(new URL(import.meta.url).pathname), "../public/exlib");
const rot = (px, py, cx, cy, a) => {
  const c = Math.cos(a), s = Math.sin(a);
  const dx = px - cx, dy = py - cy;
  return { x: cx + dx * c - dy * s, y: cy + dx * s + dy * c };
};
const N = (n) => Math.round(n * 10) / 10;

function elToStrokes(e) {
  const cx = e.x + (e.width || 0) / 2, cy = e.y + (e.height || 0) / 2, a = e.angle || 0;
  const R = (x, y) => (a ? rot(x, y, cx, cy, a) : { x, y });
  switch (e.type) {
    case "line": case "arrow": case "freedraw":
      return [{ pts: (e.points || []).map((p) => { const q = R(e.x + p[0], e.y + p[1]); return { x: N(q.x), y: N(q.y) }; }), close: false }];
    case "rectangle":
      return [{ pts: [[e.x, e.y], [e.x + e.width, e.y], [e.x + e.width, e.y + e.height], [e.x, e.y + e.height]].map(([x, y]) => { const q = R(x, y); return { x: N(q.x), y: N(q.y) }; }), close: true }];
    case "diamond":
      return [{ pts: [[cx, e.y], [e.x + e.width, cy], [cx, e.y + e.height], [e.x, cy]].map(([x, y]) => { const q = R(x, y); return { x: N(q.x), y: N(q.y) }; }), close: true }];
    case "ellipse": {
      const pts = [];
      for (let i = 0; i < 16; i++) {
        const t = (i / 16) * Math.PI * 2;
        const q = R(cx + (e.width / 2) * Math.cos(t), cy + (e.height / 2) * Math.sin(t));
        pts.push({ x: N(q.x), y: N(q.y) });
      }
      return [{ pts, close: true }];
    }
    default:
      return []; // text/image/etc: skip
  }
}

const out = {};
for (const file of readdirSync(DIR).filter((f) => f.endsWith(".excalidrawlib"))) {
  const lib = file.replace(/\.excalidrawlib$/, "");
  const data = JSON.parse(readFileSync(path.join(DIR, file), "utf8"));
  const items = data.libraryItems || (data.library || []).map((els, i) => ({ name: `item${i}`, elements: els }));
  out[lib] = {};
  for (const item of items) {
    const strokes = (item.elements || []).filter((e) => !e.isDeleted).flatMap(elToStrokes);
    if (!strokes.length) continue;
    const xs = strokes.flatMap((s) => s.pts.map((p) => p.x));
    const ys = strokes.flatMap((s) => s.pts.map((p) => p.y));
    const x0 = Math.min(...xs), y0 = Math.min(...ys);
    for (const s of strokes) s.pts = s.pts.map((p) => ({ x: N(p.x - x0), y: N(p.y - y0) }));
    out[lib][item.name || `item${Object.keys(out[lib]).length}`] = {
      w: N(Math.max(...xs) - x0),
      h: N(Math.max(...ys) - y0),
      strokes,
    };
  }
}

const ts = `// Generated by tools/exlib_convert.mjs — MIT-licensed Excalidraw community
// libraries, normalized to {w,h,strokes} for SketchPath rendering.
import { Pt } from "../motion/primitives";
export type ExStroke = { pts: Pt[]; close: boolean };
export const EXLIB: Record<string, Record<string, { w: number; h: number; strokes: ExStroke[] }>> = ${JSON.stringify(out)};
`;
writeFileSync(path.resolve(DIR, "../../src/sketch/exlib-data.ts"), ts);
let n = 0;
for (const lib of Object.keys(out)) for (const it of Object.keys(out[lib])) n++;
console.log(`wrote ${n} items from ${Object.keys(out).length} libraries`);
for (const lib of Object.keys(out)) console.log(` ${lib}: ${Object.keys(out[lib]).join(", ")}`);
